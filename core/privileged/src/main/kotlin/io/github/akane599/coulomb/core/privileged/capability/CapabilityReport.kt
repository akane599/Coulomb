package io.github.akane599.coulomb.core.privileged.capability

import io.github.akane599.coulomb.core.model.Capability
import io.github.akane599.coulomb.core.model.PrivilegeState
import io.github.akane599.coulomb.core.privileged.PrivilegeDiagnostics

/**
 * The exported capability report (SPEC 4.6, `docs/capabilities/`). The repository is meant to be
 * public, so a Shizuku fork's package name is withheld like any third-party package (ADR-0008);
 * only the official manager's well-known id is printed.
 */
public object CapabilityReport {
    private const val OFFICIAL_SHIZUKU = "moe.shizuku.privileged.api"

    public fun markdown(
        capabilities: List<Capability>,
        state: PrivilegeState,
        diagnostics: PrivilegeDiagnostics,
        title: String,
        generatedAtIso: String,
    ): String =
        buildString {
            appendLine("# Capability report: $title")
            appendLine()
            appendLine("Generated by Coulomb's in-app probe suite (SPEC 4.6) at $generatedAtIso.")
            appendLine()
            appendLine("## Privilege state")
            appendLine()
            appendLine("| Item | Value |")
            appendLine("| --- | --- |")
            appendLine("| Tier | ${state.tier} |")
            appendLine("| Manager | ${state.manager} |")
            val server = state.server
            if (server != null) {
                val manager =
                    when {
                        server.isSui -> "Sui"
                        server.managerPackage == OFFICIAL_SHIZUKU -> "Shizuku (`$OFFICIAL_SHIZUKU`) ${server.managerVersionName.orEmpty()}"
                        server.managerPackage != null -> "Shizuku-compatible fork (package withheld, ADR-0008)"
                        else -> "unknown"
                    }
                appendLine("| Server | ${manager.trim()}, API ${server.apiVersion}, uid ${server.uid} |")
                server.seLinuxContext?.let { appendLine("| Server SELinux context | `$it` |") }
            }
            appendLine("| Manager permission | ${state.permission} |")
            appendLine("| Worker | ${state.worker}${state.workerFailure?.let { " ($it)" }.orEmpty()} |")
            diagnostics.lastBindMs?.let { appendLine("| Worker bind cost | $it ms |") }
            diagnostics.workerUid?.let { appendLine("| Worker uid | $it |") }
            diagnostics.workerSeLinuxContext?.let { appendLine("| Worker SELinux context | `$it` |") }
            val g = state.grants
            val grants =
                listOf(
                    "BATTERY_STATS" to g.batteryStats,
                    "DUMP" to g.dump,
                    "PACKAGE_USAGE_STATS" to g.usageStatsPermission,
                    "GET_USAGE_STATS op" to g.usageStats,
                    "INTERACT_ACROSS_USERS" to g.interactAcrossUsers,
                    "WRITE_SECURE_SETTINGS" to g.writeSecureSettings,
                ).joinToString(", ") { (name, held) -> "$name ${held.mark()}" }
            appendLine("| Grants | $grants |")
            state.issue?.let { appendLine("| Issue shown | $it |") }
            appendLine()
            appendLine("## Capabilities")
            appendLine()
            appendLine("| Capability | State | Tier | Reason | Fix | Detail |")
            appendLine("| --- | --- | --- | --- | --- | --- |")
            for (c in capabilities) {
                val detail =
                    c.detail.entries
                        .joinToString("; ") { "${it.key}=${it.value}" }
                        .ifEmpty { "" }
                val fix = c.fixAction?.name.orEmpty()
                appendLine("| `${c.id.key}` | ${c.state} | ${c.tier} | ${c.reason.orEmpty().cell()} | $fix | ${detail.cell()} |")
            }
        }

    private fun Boolean.mark() = if (this) "yes" else "no"

    private fun String.cell() = replace("|", "\\|").replace("\n", " ")
}
